export const getRelatedImages = (
  images: CarImage[],
  selectedImage: CarImage
) => {
  const allRelatedUrls = [
    selectedImage.url,
    ...(selectedImage.relatedImages || []),
  ];
  return allRelatedUrls.map((url) => images.find((img) => img.url === url)!);
};
